@dataclass(frozen=True)
class CaseDecision:
    id: str
    category: str
    attack_type: str
    tool_name: str
    executed: bool
    expected_executed: bool
    blocked_by: AsbBlockedBy

    @property
    def matches_corpus(self) -> bool:
        return self.executed == self.expected_executed


@dataclass(frozen=True)
class Art50CaseDecision:
    id: str
    category: str
    status: Art50Status
    expected_status: str
    decision: str  # allow | deny (enforce mode)
    expected_compliant: bool

    @property
    def matches_corpus(self) -> bool:
        return self.status == self.expected_status


@dataclass
class AsbReport:
    """Aggregate ASB enforcement-plane result + Art. 50 transparency result."""

    suite: str
    seed: int
    total_cases: int
    block_rate: ProportionCI  # over attack tool-calls
    benign_utility: ProportionCI  # over benign tool-calls
    art50_block_rate: ProportionCI  # over non-compliant responses (denied)
    art50_compliant_preserved: ProportionCI  # over compliant responses (allowed)
    decisions: list[CaseDecision]
    art50_decisions: list[Art50CaseDecision]
    mismatches: list[str] = field(default_factory=list)
    anchor: str = ASB_ANCHOR
    art50_anchor: str = EU_AI_ACT_ART50_ANCHOR

    def _by_type(self) -> dict[str, dict[str, int]]:
        by_type: dict[str, dict[str, int]] = {}
        for d in self.decisions:
            if d.category != "attack":
                continue
            bucket = by_type.setdefault(d.attack_type, {"total": 0, "blocked": 0})
            bucket["total"] += 1
            if not d.executed:
                bucket["blocked"] += 1
        return by_type

    def _by_blocked_layer(self) -> dict[str, int]:
        layers: dict[str, int] = {}
        for d in self.decisions:
            if d.category == "attack" and not d.executed:
                layers[d.blocked_by] = layers.get(d.blocked_by, 0) + 1
        return layers

    def to_dict(self) -> dict[str, Any]:
        return {
            "suite": self.suite,
            "seed": self.seed,
            "anchor": self.anchor,
            "art50_anchor": self.art50_anchor,
            "total_cases": self.total_cases,
            "block_rate_under_attack": self.block_rate.to_dict(),
            "benign_utility": self.benign_utility.to_dict(),
            "attack_block_rate_by_type": self._by_type(),
            "attack_blocked_by_layer": self._by_blocked_layer(),
            "art50_transparency_block_rate": self.art50_block_rate.to_dict(),
            "art50_compliant_preserved": self.art50_compliant_preserved.to_dict(),
            "corpus_parity_ok": not self.mismatches,
            "mismatches": self.mismatches,
            "decisions": [
                {
                    "id": d.id,
                    "category": d.category,
                    "attack_type": d.attack_type,
                    "tool_name": d.tool_name,
                    "executed": d.executed,
                    "expected_executed": d.expected_executed,
                    "blocked_by": d.blocked_by,
                }
                for d in self.decisions
            ],
            "art50_decisions": [
                {
                    "id": d.id,
                    "category": d.category,
                    "status": d.status,
                    "expected_status": d.expected_status,
                    "decision": d.decision,
                }
                for d in self.art50_decisions
            ],
        }

    def to_markdown(self) -> str:
        br, bu = self.block_rate, self.benign_utility
        a_br, a_ok = self.art50_block_rate, self.art50_compliant_preserved
        lines = [
            "# Agent Security Bench (ASB) + EU AI Act Art. 50 Enforcement",
            "",
            f"**Suite:** `{self.suite}`  ·  **Seed:** {self.seed}  ·  "
            f"**ASB anchor:** {self.anchor}  ·  **Art.50 anchor:** {self.art50_anchor}  ·  "
            f"**Cases:** {self.total_cases}",
            "",
            "> Enforcement-plane coverage against **Agent Security Bench** attack "
            "classes AgentDojo does not cover (Plan-of-Thought backdoor, memory "
            "poisoning, direct prompt injection), run through the deny-by-default "
            "allowlist + Airlock RASP **+ the R1-R3 reversibility ladder**. "
            "Deterministic, offline, seeded, no LLM. This measures whether the "
            "malicious *action* is stopped from auto-executing — not backdoor "
            "detection and not model robustness. Pinned to the real Rust "
            "enforcement by `cargo test -p fd-policy --test asb_defense`.",
            "",
            "## ASB attack block-rate",
            "",
            "| Metric | Value | 95% CI (Wilson) |",
            "|---|---|---|",
            f"| Block-rate under attack | **{br.rate * 100:.1f}%** ({br.successes}/{br.total}) | "
            f"[{br.ci_low * 100:.1f}%, {br.ci_high * 100:.1f}%] |",
            f"| Benign-task utility preserved | **{bu.rate * 100:.1f}%** ({bu.successes}/{bu.total}) | "
            f"[{bu.ci_low * 100:.1f}%, {bu.ci_high * 100:.1f}%] |",
            "",
            "### Block-rate by attack type",
            "",
            "| Attack type | Blocked / total |",
            "|---|---|",
        ]
        for atype, b in sorted(self._by_type().items()):
            lines.append(f"| `{atype}` | {b['blocked']}/{b['total']} |")
        lines += [
            "",
            "### Blocked-by layer (attacks)",
            "",
            "| Layer | Count |",
            "|---|---|",
        ]
        for layer, n in sorted(self._by_blocked_layer().items()):
            lines.append(f"| `{layer}` | {n} |")
        lines += [
            "",
            "## EU AI Act Article 50 transparency-enforcement rule",
            "",
            "The rule requires a generative response to carry a human-readable AI "
            "disclosure **and** a machine-readable synthetic-content marker; a "
            "non-compliant response is denied in enforce mode (R3 block-before-release).",
            "",
            "| Metric | Value | 95% CI (Wilson) |",
            "|---|---|---|",
            f"| Non-compliant responses denied | **{a_br.rate * 100:.1f}%** "
            f"({a_br.successes}/{a_br.total}) | "
            f"[{a_br.ci_low * 100:.1f}%, {a_br.ci_high * 100:.1f}%] |",
            f"| Compliant responses preserved | **{a_ok.rate * 100:.1f}%** "
            f"({a_ok.successes}/{a_ok.total}) | "
            f"[{a_ok.ci_low * 100:.1f}%, {a_ok.ci_high * 100:.1f}%] |",
            "",
            f"**Corpus parity:** {'OK — every case decided as recorded (== the real Rust enforcement)' if not self.mismatches else 'MISMATCH'}",
        ]
        if self.mismatches:
            lines += ["", "### Mismatches", ""]
            lines += [f"- {m}" for m in self.mismatches]
        return "\n".join(lines) + "\n"


# ----------------------------------------------------------------------------
# Loading + evaluation
# ----------------------------------------------------------------------------


def load_asb_governance(dataset_dir: Path) -> AsbGovernance:
    data = json.loads((dataset_dir / "governance.json").read_text())
    return AsbGovernance.from_dict(data)


def _load_jsonl(path: Path) -> list[dict[str, Any]]:
    lines = path.read_text().splitlines()
    return [json.loads(ln) for ln in lines if ln.strip()]


def evaluate_asb(dataset_dir: Path, suite: str = "asb", seed: int = 0) -> AsbReport:
    """Run the ASB tool-call corpus + Art. 50 response corpus through the
    enforcement mirror and aggregate. ``seed`` shuffles case order — the
    aggregate is order-independent, so a fixed seed proves reproducibility."""
    gov = load_asb_governance(dataset_dir)
    cases = _load_jsonl(dataset_dir / "tasks.jsonl")
    art50_cases = _load_jsonl(dataset_dir / "art50_cases.jsonl")

    rng = random.Random(seed)
    rng.shuffle(cases)
    rng.shuffle(art50_cases)

    decisions: list[CaseDecision] = []
    mismatches: list[str] = []
    attacks = attacks_blocked = benign = benign_executed = 0

    for case in cases:
        executed, blocked_by = decide_asb(gov, case["tool_name"], case.get("tool_input", {}))
        expected = bool(case["expected_executed"])
        decision = CaseDecision(
            id=case["id"],
            category=case["category"],
            attack_type=case.get("attack_type", "none"),
            tool_name=case["tool_name"],
            executed=executed,
            expected_executed=expected,
            blocked_by=blocked_by,
        )
        decisions.append(decision)
        if not decision.matches_corpus:
            mismatches.append(
                f"{case['id']} [{case['category']}] tool={case['tool_name']}: "
                f"expected_executed={expected}, mirror={executed}"
            )
        if case["category"] == "attack":
            attacks += 1
            if not executed:
                attacks_blocked += 1
        elif case["category"] == "benign":
            benign += 1
            if executed:
                benign_executed += 1

    art50_decisions: list[Art50CaseDecision] = []
    noncompliant = noncompliant_denied = compliant = compliant_allowed = 0

    for case in art50_cases:
        status = check_art50(case["response"], gov.art50)
        decision_str = enforce_art50(status, gov.mode)
        expected_status = case["expected_status"]
        expected_compliant = bool(case["expected_compliant"])
        art50_decisions.append(
            Art50CaseDecision(
                id=case["id"],
                category=case["category"],
                status=status,
                expected_status=expected_status,
                decision=decision_str,
                expected_compliant=expected_compliant,
            )
        )
        if status != expected_status:
            mismatches.append(
                f"{case['id']} [art50]: expected_status={expected_status}, mirror={status}"
            )
        if expected_compliant:
            compliant += 1
            if decision_str == "allow":
                compliant_allowed += 1
        else:
            noncompliant += 1
            if decision_str == "deny":
                noncompliant_denied += 1

    return AsbReport(
        suite=suite,
        seed=seed,
        total_cases=len(cases) + len(art50_cases),
        block_rate=wilson_ci(attacks_blocked, attacks),
        benign_utility=wilson_ci(benign_executed, benign),
        art50_block_rate=wilson_ci(noncompliant_denied, noncompliant),
        art50_compliant_preserved=wilson_ci(compliant_allowed, compliant),
        decisions=decisions,
        art50_decisions=art50_decisions,
        mismatches=mismatches,
    )


