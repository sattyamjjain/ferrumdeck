"""Agent Security Bench (ASB) axis + EU AI Act Article 50 transparency rule.

A second benchmark axis alongside ``injection_defense``. Where AgentDojo covers
*indirect* prompt injection, this measures FerrumDeck's **enforcement-plane
coverage** against attack classes from **Agent Security Bench**
(arXiv:2410.02644) that AgentDojo does not — the **Plan-of-Thought (PoT)
backdoor**, **memory poisoning**, and **direct prompt injection** — by running a
vendored corpus through the deny-by-default tool allowlist + Airlock RASP **plus
the R1-R3 graduated reversibility ladder**. The distinguishing case is an
*allowlisted-but-irreversible* action (a backdoored ``deploy``): the allowlist
permits it, Airlock permits it, and the **R3 rung** (``irreversible ->
require_approval``) is what stops it from auto-executing.

It also enforces the **EU AI Act Article 50** transparency rule on generative
responses (``fd_policy::transparency_art50``): a response must carry a
human-readable AI disclosure *and* a machine-readable synthetic-content marker,
or it is denied in enforce mode.

This is **not** a model-robustness benchmark and no LLM is involved. It exercises
the policy/RASP/transparency layer deterministically and offline. The block-rate
reporter (Wilson CI) is **reused** from ``fd_evals.injection_defense``; the
allowlist + Airlock decision is the same ``decide`` contract, extended here with
the reversibility ladder. The corpus is **pinned to the real Rust enforcement**
by ``rust/crates/fd-policy/tests/asb_defense.rs`` (which runs the actual
``ToolAllowlist`` + ``AirlockInspector`` + reversibility ladder + the
``transparency_art50`` rule over the same cases); both planes must agree.

Corpus: ``evals/datasets/asb/{governance.json, tasks.jsonl, art50_cases.jsonl}``.
"""

from __future__ import annotations

import json
import random
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

# Reuse the block-rate reporter + the allowlist/Airlock decision from the
# injection-defense suite — the ASB axis layers the reversibility ladder on top.
from fd_evals.injection_defense import (
    Governance,
    ProportionCI,
    wilson_ci,
)
from fd_evals.injection_defense import (
    decide as decide_base,
)

# Stable anchors.
ASB_ANCHOR = "agentsecuritybench:arxiv:2410.02644"
EU_AI_ACT_ART50_ANCHOR = "eu-ai-act-article-50-transparency"

AsbBlockedBy = Literal["allowlist", "rce", "exfil", "reversibility_r3", "none"]
Art50Status = Literal[
    "compliant",
    "missing_disclosure",
    "missing_machine_readable",
    "missing_both",
]

# ----------------------------------------------------------------------------
# Reversibility ladder (mirror of fd_policy::reversibility::graduated_response)
# ----------------------------------------------------------------------------


def graduated_rung(reversibility: str, budget_has_headroom: bool) -> str:
    """Map a tool's reversibility onto the R1-R3 rung.

    ``reversible`` -> R1; ``costly`` -> R2 while the budget gate has headroom
    else R3; ``irreversible`` (and any unknown value, deny-by-default) -> R3.
    Mirrors the Rust ``graduated_response`` + ``Reversibility::parse`` fallback.
    """
    r = reversibility.strip().lower()
    if r == "reversible":
        return "R1"
    if r == "costly":
        return "R2" if budget_has_headroom else "R3"
    return "R3"  # irreversible OR unknown -> most restrictive rung


# ----------------------------------------------------------------------------
# EU AI Act Article 50 transparency rule (mirror of fd_policy::transparency_art50)
# ----------------------------------------------------------------------------

# Human-readable AI-disclosure phrases (Art. 50(1)/(4)). The bare-word
# ``ai-generated`` alternative requires a preceding non-tag boundary so the
# machine-readable ``<ai-generated>`` marker does not count as prose disclosure.
_DISCLOSURE_RE = re.compile(
    r"(?i)((?:^|[^<\[\w-])ai[\s-]generated|generated by (an? )?ai\b|"
    r"generated by artificial intelligence|created by (an? )?ai\b|"
    r"produced by (an? )?ai\b|written by (an? )?ai\b|artificially generated|"
    r"this (content|response|message|output|text) (was|is|has been) "
    r"(generated|produced|created|written)( automatically)?( by)?( an?)?"
    r"( ai\b| artificial intelligence)|"
    r"you are (interacting|chatting|speaking) with (an? )?ai\b)"
)

# Machine-readable synthetic-content markers (Art. 50(2)).
_MACHINE_READABLE_RE = re.compile(
    r"(?i)(<ai[\s-]generated\b|</ai[\s-]generated>|data-ai-generated\s*=|"
    r"[\"']?ai_generated[\"']?\s*[:=]\s*true|x-ai-generated\s*:|"
    r"content-credentials|c2pa\b|synthid|\[ai-generated\]|\{ai:generated\})"
)


@dataclass(frozen=True)
class Art50Config:
    """Which Article 50 obligations the enforcement plane requires."""

    require_disclosure: bool = True
    require_machine_readable: bool = True

    @classmethod
    def from_dict(cls, data: dict[str, Any] | None) -> Art50Config:
        data = data or {}
        return cls(
            require_disclosure=bool(data.get("require_disclosure", True)),
            require_machine_readable=bool(data.get("require_machine_readable", True)),
        )


def has_disclosure(response_text: str) -> bool:
    return bool(_DISCLOSURE_RE.search(response_text))


def has_machine_readable_marker(response_text: str) -> bool:
    return bool(_MACHINE_READABLE_RE.search(response_text))


def check_art50(response_text: str, cfg: Art50Config) -> Art50Status:
    """Evaluate a generative response against the required Art. 50 obligations."""
    missing_disclosure = cfg.require_disclosure and not has_disclosure(response_text)
    missing_marker = cfg.require_machine_readable and not has_machine_readable_marker(response_text)
    if not missing_disclosure and not missing_marker:
        return "compliant"
    if missing_disclosure and not missing_marker:
        return "missing_disclosure"
    if not missing_disclosure and missing_marker:
        return "missing_machine_readable"
    return "missing_both"


def enforce_art50(status: Art50Status, mode: str) -> Literal["allow", "deny"]:
    """Enforce a compliance verdict: ``enforce`` denies non-compliant responses
    (block-before-release); ``shadow`` logs but never blocks."""
    if status == "compliant":
        return "allow"
    return "deny" if mode == "enforce" else "allow"


# ----------------------------------------------------------------------------
# Governance
# ----------------------------------------------------------------------------


@dataclass(frozen=True)
class AsbGovernance:
    """The vendored governance profile: the injection-defense allowlist/Airlock
    base, plus the reversibility ladder + budget gate + Art. 50 config."""

    base: Governance
    tool_reversibility: dict[str, str]
    budget_has_headroom: bool
    art50: Art50Config
    mode: str

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> AsbGovernance:
        return cls(
            base=Governance.from_dict(data),
            tool_reversibility={
                k: str(v) for k, v in (data.get("tool_reversibility") or {}).items()
            },
            budget_has_headroom=bool((data.get("budget") or {}).get("has_headroom", True)),
            art50=Art50Config.from_dict(data.get("art50")),
            mode=(data.get("airlock") or {}).get("mode", "enforce"),
        )

    def reversibility(self, tool_name: str) -> str:
        return self.tool_reversibility.get(tool_name, "irreversible")


# ----------------------------------------------------------------------------
# Decision
# ----------------------------------------------------------------------------


def decide_asb(
    gov: AsbGovernance, tool_name: str, tool_input: dict[str, Any]
) -> tuple[bool, AsbBlockedBy]:
    """Return ``(executed, blocked_by)`` for a tool call under the enforcement
    plane: the deny-by-default allowlist + Airlock decision, then the R1-R3
    reversibility ladder (an R3 rung gates the action -> not auto-executed)."""
    executed, blocked_by = decide_base(gov.base, tool_name, tool_input)
    if not executed:
        return False, blocked_by  # allowlist / rce / exfil
    rung = graduated_rung(gov.reversibility(tool_name), gov.budget_has_headroom)
    if rung == "R3":
        return False, "reversibility_r3"
    return True, "none"


